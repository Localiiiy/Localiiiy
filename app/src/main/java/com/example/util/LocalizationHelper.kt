/**
 * Global Multi-Language Localization Engine for Localiiiy.
 * Provides instant translation dictionaries and localized strings
 * for international distribution across North America, Latin America, Europe,
 * Asia-Pacific, Africa, and the Middle East.
 */
enum class LocaliLanguage(
    val code: String,
    val displayName: String,
    val nativeName: String,
    val flag: String,
    val isRtl: Boolean = false
) {
    EN("en", "English", "English (US)", "🇺🇸"),
    ES("es", "Spanish", "Español", "🇪🇸"),
    FR("fr", "French", "Français", "🇫🇷"),
    DE("de", "German", "Deutsch", "🇩🇪"),
    HI("hi", "Hindi", "हिन्दी", "🇮🇳"),
    ZH("zh", "Chinese", "中文 (简体)", "🇨🇳"),
    JA("ja", "Japanese", "日本語", "🇯🇵"),
    PT("pt", "Portuguese", "Português", "🇧🇷"),
    AR("ar", "Arabic", "العربية", "🇸🇦", isRtl = true),
    RU("ru", "Russian", "Русский", "🇷🇺"),
    BN("bn", "Bengali", "বাংলা", "🇧🇩"),
    ID("id", "Indonesian", "Bahasa Indonesia", "🇮🇩"),
    KO("ko", "Korean", "한국어", "🇰🇷"),
    IT("it", "Italian", "Italiano", "🇮🇹"),
    TR("tr", "Turkish", "Türkçe", "🇹🇷"),
    SW("sw", "Swahili", "Kiswahili", "🇰🇪"),
    VI("vi", "Vietnamese", "Tiếng Việt", "🇻🇳"),
    UR("ur", "Urdu", "اردو", "🇵🇰", isRtl = true);

    companion object {
        val ALL: List<LocaliLanguage> = entries.toList()

        fun fromCode(code: String?): LocaliLanguage {
            if (code.isNullOrBlank()) return EN
            return entries.find { it.code.equals(code, ignoreCase = true) } ?: EN
        }
    }
}

